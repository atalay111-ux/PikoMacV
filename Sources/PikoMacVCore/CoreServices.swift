import AppKit
import LocalAuthentication
import PikoMacVKit
import ServiceManagement
import UniformTypeIdentifiers

@MainActor
public final class CoreServices: CoreActions {
    let state: AppState
    let paths = StoragePaths()
    let ioQueue = DispatchQueue(label: "com.pikomacv.core.io", qos: .utility)

    var timer: Timer?
    var lastChangeCount = NSPasteboard.general.changeCount
    var ownChangeCount: Int = -1
    var lastExternalApp: TargetApp?
    /// Tanılama (`--debug-hooks`): panelin hedef uygulamasını sabitler.
    public var debugTargetOverride: TargetApp?
    var activationObserver: NSObjectProtocol?
    var saveWork: DispatchWorkItem?
    var lastAuth: Date?
    var copying: Set<UUID> = []
    let thumbCache = NSCache<NSString, NSImage>()

    public init(state: AppState) {
        self.state = state
        thumbCache.countLimit = 300
    }

    // MARK: - Başlatma

    public func start() {
        paths.prepare()
        if let h = JSONStore.load([ClipItem].self, from: paths.history) { state.items = h }
        if let p = JSONStore.load([PinnedItem].self, from: paths.pins) { state.pins = p }
        if let s = JSONStore.load(Settings.self, from: paths.settings) { state.settings = s }
        applyHistoryLimit()
        recomputeVault()
        cleanCache()

        // Tanılama: demo örneği panoyu ne okur ne yazar.
        if CommandLine.arguments.contains("--debug-hooks"),
           ProcessInfo.processInfo.environment["PIKOMACV_NO_MONITOR"] == "1" { return }

        if let app = NSWorkspace.shared.frontmostApplication, app.processIdentifier != getpid() {
            lastExternalApp = makeTarget(app)
        }
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main
        ) { [weak self] note in
            let app = note.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication
            MainActor.assumeIsolated {
                guard let self, let app, app.processIdentifier != getpid() else { return }
                self.lastExternalApp = self.makeTarget(app)
            }
        }

        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    // MARK: - PikoMacV izleme

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func poll() {
        let pb = NSPasteboard.general
        let cc = pb.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc
        if cc == ownChangeCount { return }
        let types = pb.types ?? []
        if types.contains(where: { Self.skipTypes.contains($0) }) { return }
        let front = NSWorkspace.shared.frontmostApplication
        if let bid = front?.bundleIdentifier, state.settings.ignoredBundleIDs.contains(bid) { return }
        guard var item = classify(pb) else { return }
        item.sourceAppName = front?.localizedName
        item.sourceBundleID = front?.bundleIdentifier
        record(item, pasteboard: pb)
    }

    /// PikoMacVdaki içeriği bir ClipItem'a çevirir (blob'lar henüz yazılmaz).
    private func classify(_ pb: NSPasteboard) -> ClipItem? {
        let urls = (pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]) ?? []
        if !urls.isEmpty {
            let fm = FileManager.default
            let refs: [FileRef] = urls.map { u in
                let vals = try? u.resourceValues(forKeys: [.isDirectoryKey, .fileSizeKey])
                let isDir = vals?.isDirectory ?? false
                var size = Int64(vals?.fileSize ?? 0)
                if size == 0, !isDir, let a = try? fm.attributesOfItem(atPath: u.path),
                   let n = a[.size] as? NSNumber { size = n.int64Value }
                return FileRef(originalPath: u.path, name: u.lastPathComponent, byteSize: isDir ? 0 : size, isDirectory: isDir)
            }
            return ClipItem(kind: .file, files: refs, contentHash: Hashing.hex("file:" + refs.map(\.originalPath).joined(separator: "\n")))
        }
        let imgData = pb.data(forType: .png) ?? pb.data(forType: .tiff)
        if let d = imgData, let rep = NSBitmapImageRep(data: d),
           let png = rep.representation(using: .png, properties: [:]) {
            var item = ClipItem(kind: .image, imageWidth: rep.pixelsWide, imageHeight: rep.pixelsHigh,
                                contentHash: Hashing.hex(png))
            pendingPNG = png
            item.imageBlob = ""   // kayıtta gerçek ada çevrilir
            return item
        }
        if let s = pb.string(forType: .string) {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            if trimmed.isEmpty { return nil }
            var kind = ClipKind.text
            if !trimmed.contains(where: { $0.isWhitespace }), let u = URL(string: trimmed),
               let sch = u.scheme?.lowercased(), sch == "http" || sch == "https", u.host != nil {
                kind = .link
            }
            let item = ClipItem(kind: kind, text: s, contentHash: Hashing.hex("text:" + s))
            pendingRTF = pb.data(forType: .rtf)
            return item
        }
        return nil
    }

    // classify'dan kayda geçici veri aktarımı
    var pendingPNG: Data?
    var pendingRTF: Data?

    private func record(_ newItem: ClipItem, pasteboard: NSPasteboard) {
        var item = newItem
        defer { pendingPNG = nil; pendingRTF = nil }
        if let idx = state.items.firstIndex(where: { $0.contentHash == item.contentHash }) {
            var existing = state.items.remove(at: idx)
            existing.createdAt = Date()
            existing.sourceAppName = item.sourceAppName ?? existing.sourceAppName
            existing.sourceBundleID = item.sourceBundleID ?? existing.sourceBundleID
            if item.kind == .file { existing.files = mergeFiles(existing.files, item.files) }
            state.items.insert(existing, at: 0)
            if existing.kind == .file { startCopies(for: existing.id) }
            itemsChanged()
            return
        }
        if item.kind == .image {
            if let png = pendingPNG {
                let name = UUID().uuidString + ".png"
                do { try png.write(to: paths.blobURL(name), options: .atomic); item.imageBlob = name }
                catch { return }
            } else { return }
        }
        if let rtf = pendingRTF, item.kind == .text || item.kind == .link {
            let name = UUID().uuidString + ".rtf"
            if (try? rtf.write(to: paths.blobURL(name), options: .atomic)) != nil { item.rtfBlob = name }
        }
        state.items.insert(item, at: 0)
        applyHistoryLimit()
        itemsChanged()
        if item.kind == .file { startCopies(for: item.id) }
    }

    /// Yinelenen dosya öğesinde mevcut kopyaları koru.
    private func mergeFiles(_ old: [FileRef], _ new: [FileRef]) -> [FileRef] {
        new.map { n in
            if let o = old.first(where: { $0.originalPath == n.originalPath }), o.storedCopy != nil { return o }
            return n
        }
    }

    // MARK: - Geçmiş ve sınırlar

    func itemsChanged() {
        recomputeVault()
        scheduleSave()
    }

    func applyHistoryLimit() {
        let limit = max(1, state.settings.historyLimit)
        if state.items.count > limit {
            let removed = state.items[limit...]
            removed.forEach(deleteAssets)
            state.items.removeSubrange(limit...)
        }
    }

    func deleteAssets(of item: ClipItem) {
        let fm = FileManager.default
        if let b = item.imageBlob, !b.isEmpty { try? fm.removeItem(at: paths.blobURL(b)) }
        if let r = item.rtfBlob { try? fm.removeItem(at: paths.blobURL(r)) }
        for f in item.files { removeStoredCopy(f.storedCopy) }
        thumbCache.removeObject(forKey: item.id.uuidString as NSString)
    }

    func removeStoredCopy(_ stored: String?) {
        guard let stored else { return }
        // "uuid/ad" biçiminde: tüm klasörü sil
        let dir = paths.vaultURL(stored).deletingLastPathComponent()
        if dir.standardizedFileURL != paths.vault.standardizedFileURL {
            try? FileManager.default.removeItem(at: dir)
        } else {
            try? FileManager.default.removeItem(at: paths.vaultURL(stored))
        }
    }

    public func delete(_ item: ClipItem) {
        guard let idx = state.items.firstIndex(where: { $0.id == item.id }) else { return }
        let removed = state.items.remove(at: idx)
        deleteAssets(of: removed)
        itemsChanged()
    }

    public func clearHistory() {
        state.items.forEach(deleteAssets)
        state.items.removeAll()
        itemsChanged()
    }

    // MARK: - Dosya deposu

    func recomputeVault() {
        let a = state.items.reduce(Int64(0)) { $0 + $1.storedBytes }
        let b = state.pins.reduce(Int64(0)) { $0 + $1.item.storedBytes }
        state.vaultUsedBytes = a + b
    }

    func startCopies(for id: UUID) {
        guard !copying.contains(id), let item = state.items.first(where: { $0.id == id }) else { return }
        let limit = state.settings.maxFileCopyBytes
        let jobs = item.files.enumerated().filter { _, f in
            f.storedCopy == nil && !f.isDirectory && f.byteSize <= limit
        }.map { ($0.offset, $0.element.originalPath, $0.element.name) }
        guard !jobs.isEmpty else { return }
        copying.insert(id)
        let vault = paths.vault
        ioQueue.async { [weak self] in
            var results: [(Int, String, Int64)] = []
            for (i, src, name) in jobs {
                let sub = UUID().uuidString
                let dir = vault.appendingPathComponent(sub, isDirectory: true)
                let dst = dir.appendingPathComponent(name)
                do {
                    try FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
                    try FileManager.default.copyItem(atPath: src, toPath: dst.path)
                    let size = ((try? FileManager.default.attributesOfItem(atPath: dst.path))?[.size] as? NSNumber)?.int64Value ?? 0
                    results.append((i, sub + "/" + name, size))
                } catch {
                    try? FileManager.default.removeItem(at: dir)
                }
            }
            Task { @MainActor [weak self] in self?.copiesFinished(id: id, results: results) }
        }
    }

    private func copiesFinished(id: UUID, results: [(Int, String, Int64)]) {
        copying.remove(id)
        guard let idx = state.items.firstIndex(where: { $0.id == id }) else {
            results.forEach { removeStoredCopy($0.1) }   // öğe bu arada silindi
            return
        }
        for (i, stored, size) in results where i < state.items[idx].files.count {
            state.items[idx].files[i].storedCopy = stored
            state.items[idx].files[i].byteSize = size
        }
        enforceVaultCap()
        itemsChanged()
    }

    func enforceVaultCap() {
        recomputeVault()
        let cap = state.settings.vaultCapBytes
        guard state.vaultUsedBytes > cap else { return }
        for i in stride(from: state.items.count - 1, through: 0, by: -1) {
            if state.vaultUsedBytes <= cap { break }
            for j in state.items[i].files.indices {
                if let s = state.items[i].files[j].storedCopy {
                    removeStoredCopy(s)
                    state.items[i].files[j].storedCopy = nil
                }
            }
            recomputeVault()
        }
    }

    public func evictionRisk(of item: ClipItem) -> Double {
        let cap = Double(max(1, state.settings.vaultCapBytes))
        let ratio = Double(state.vaultUsedBytes) / cap
        guard item.storedBytes > 0, ratio >= 0.6 else { return 0 }
        let fullness = min(1, max(0, (ratio - 0.6) / 0.4))
        // items en yeni başta; eskiden yeniye sırala
        let candidates = state.items.reversed().filter { $0.storedBytes > 0 }
        guard let rank = candidates.firstIndex(where: { $0.id == item.id }) else { return 0 }
        return fullness * (1 - Double(rank) / Double(candidates.count))
    }

    // MARK: - Kayıt

    func scheduleSave() {
        saveWork?.cancel()
        let w = DispatchWorkItem { [weak self] in MainActor.assumeIsolated { self?.saveNow() } }
        saveWork = w
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.6, execute: w)
    }

    func saveNow() {
        let items = JSONStore.encode(state.items)
        let pins = JSONStore.encode(state.pins)
        let settings = JSONStore.encode(state.settings)
        let p = paths
        ioQueue.async {
            try? FileManager.default.createDirectory(at: p.root, withIntermediateDirectories: true)
            if let items { try? items.write(to: p.history, options: .atomic) }
            if let pins { try? pins.write(to: p.pins, options: .atomic) }
            if let settings { try? settings.write(to: p.settings, options: .atomic) }
        }
    }

    public func settingsChanged() {
        applyHistoryLimit()
        enforceVaultCap()
        itemsChanged()
        let service = SMAppService.mainApp
        do {
            if state.settings.launchAtLogin {
                if service.status != .enabled { try service.register() }
            } else if service.status == .enabled {
                try service.unregister()
            }
        } catch {
            // İmzasız geliştirme sürümlerinde başarısız olabilir; yok say.
        }
    }

    func cleanCache() {
        let dir = paths.cache
        ioQueue.async {
            let files = (try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.contentModificationDateKey])) ?? []
            for f in files {
                let d = (try? f.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate
                if let d, Date().timeIntervalSince(d) > 86_400 { try? FileManager.default.removeItem(at: f) }
            }
        }
    }

    // MARK: - Hedef uygulama

    func makeTarget(_ app: NSRunningApplication) -> TargetApp {
        TargetApp(bundleID: app.bundleIdentifier,
                  name: app.localizedName ?? app.bundleIdentifier ?? "?",
                  category: TargetRules.category(for: app.bundleIdentifier),
                  pid: app.processIdentifier)
    }

    public func currentTarget() -> TargetApp? {
        if let t = debugTargetOverride { return t }
        if let app = NSWorkspace.shared.frontmostApplication, app.processIdentifier != getpid() {
            return makeTarget(app)
        }
        return lastExternalApp
    }

    public func suitability(of item: ClipItem, for target: TargetApp?) -> Suitability? {
        TargetRules.suitability(of: item, for: target)
    }

    // MARK: - Küçük resim ve erişilebilirlik

    public func thumbnail(for item: ClipItem) -> NSImage? {
        switch item.kind {
        case .image:
            let key = item.id.uuidString as NSString
            if let c = thumbCache.object(forKey: key) { return c }
            guard let blob = item.imageBlob, !blob.isEmpty,
                  let src = CGImageSourceCreateWithURL(paths.blobURL(blob) as CFURL, nil) else { return nil }
            let opts: [CFString: Any] = [kCGImageSourceCreateThumbnailFromImageAlways: true,
                                         kCGImageSourceCreateThumbnailWithTransform: true,
                                         kCGImageSourceThumbnailMaxPixelSize: 128]
            guard let cg = CGImageSourceCreateThumbnailAtIndex(src, 0, opts as CFDictionary) else { return nil }
            let img = NSImage(cgImage: cg, size: NSSize(width: cg.width / 2, height: cg.height / 2))
            thumbCache.setObject(img, forKey: key)
            return img
        case .file:
            guard let f = item.files.first else { return nil }
            if FileManager.default.fileExists(atPath: f.originalPath) {
                return NSWorkspace.shared.icon(forFile: f.originalPath)
            }
            let type = UTType(filenameExtension: (f.name as NSString).pathExtension) ?? .data
            return NSWorkspace.shared.icon(for: type)
        default:
            return nil
        }
    }

    public func isAvailable(_ item: ClipItem) -> Bool {
        guard item.kind == .file else { return true }
        let fm = FileManager.default
        return item.files.allSatisfy { f in
            fm.fileExists(atPath: f.originalPath)
                || (f.storedCopy.map { fm.fileExists(atPath: paths.vaultURL($0).path) } ?? false)
        }
    }
}
